def pick_nouns(n: int) -> list:
    """随机抽取 n 个互不重复的名词（数量严格等于 n，词库足够大时必然满足）。"""
    n = max(1, min(n, len(NOUN_LIBRARY)))
    return random.sample(NOUN_LIBRARY, n)


def pick_nouns_pool(total: int) -> list:
    """为整轮测试抽取 total 个名词（全局视角，供各 thread 分片使用）。

    - total <= 词库规模：无放回抽样，全部互不重复；
    - total >  词库规模：有放回抽样，允许重复（数量严格等于 total）。
    """
    total = max(1, total)
    if total <= len(NOUN_LIBRARY):
        return random.sample(NOUN_LIBRARY, total)
    return random.choices(NOUN_LIBRARY, k=total)

